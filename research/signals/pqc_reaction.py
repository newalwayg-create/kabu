def main():
    T = [c + ".T" for c in C]
    d = yf.download(T, start="2026-06-01", progress=False, auto_adjust=False, threads=True)
    Cl, V = d["Close"], d["Volume"]
    rows = []
    for t in T:
        p = Cl[t].dropna(); v = V[t].dropna()
        if len(p) < 40 or p.loc[:"2026-09-30"].empty:
            continue
        base = p.loc[:"2026-09-30"].iloc[-1]
        dl = p.diff(); up = dl.clip(lower=0).ewm(alpha=1 / 14).mean(); dn = (-dl.clip(upper=0)).ewm(alpha=1 / 14).mean()
        rows.append({"コード": t[:-2], "銘柄": C[t[:-2]][0], "分類": C[t[:-2]][1], "株価": p.iloc[-1],
                     "9/30から%": (p.iloc[-1] / base - 1) * 100, "10月の最高値まで%": (p.loc["2026-10-01":].max() / base - 1) * 100,
                     "高値から%": (p.iloc[-1] / p.loc["2026-10-01":].max() - 1) * 100, "直近5日%": (p.iloc[-1] / p.iloc[-6] - 1) * 100,
                     "出来高の増え方": v.iloc[-10:].mean() / v.iloc[-70:-10].mean(), "RSI": (100 - 100 / (1 + up / dn)).iloc[-1],
                     "代金億": (v.iloc[-20:] * p.iloc[-20:]).mean() / 1e8})
    S = pd.DataFrame(rows).set_index("コード").sort_values("9/30から%")
    pd.set_option("display.width", 250); pd.set_option("display.max_rows", 80)
    print(S.round(2).to_string())


if __name__ == "__main__":
    main()
